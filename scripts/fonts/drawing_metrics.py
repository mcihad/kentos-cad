"""The advance widths of the drawing typefaces the desktop added after the web paused (docs/adr/9311): Arial and Times
New Roman, measured from the faces the core bundles for them, their metric twins (Arimo for Arial, Liberation Serif
for Times New Roman: every letter as wide as the named face's). The web's typefaces' tables
(crates/shared/geometry-core/src/text/metrics.rs) were recorded in a browser; these are read from the files' own
advances (hmtx), which the browser's agree with (Arimo's 500 row: the same but for DEL and the soft hyphen, which
measure nothing), in thousandths of an em, weight 500 (`ADVANCES`) and 600 (`BOLD`): a face without them takes the
nearest the browser would (Liberation Serif's 400 for 500, its 700 for 600).

    .run/py/bin/python scripts/fonts/drawing_metrics.py           # writes metrics_more.rs
    .run/py/bin/python scripts/fonts/drawing_metrics.py --check   # writes nothing; fails when it would differ

Needs fontTools.
"""
import sys
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / "paket/fonts/cizim"
OUT = ROOT / "crates/shared/geometry-core/src/text/metrics_more.rs"
FIRST, LAST = 32, 383
# id, name, the 500 face, the 600 face; None: the browser's rows of the twin in metrics.rs (Arial is drawn in Arimo's
# own face, so its rows are Arimo's, line for line).
FACES = [
    ("arial", "Arial (Arimo)", None, None),
    ("times-new-roman", "Times New Roman (Liberation Serif)", "LiberationSerif-Regular.ttf", "LiberationSerif-Bold.ttf"),
]
WEB = ROOT / "crates/shared/geometry-core/src/text/metrics.rs"


def web_row(table_name: str, face: str) -> list[int]:
    """A row of metrics.rs's table, by the face's comment line (`// Arimo`)."""
    import re

    src = WEB.read_text()
    body = re.search(r"pub const " + table_name + r": \[\[u16; 352\]; \d+\] = \[(.*?)\n\];", src, re.S).group(1)
    for block in re.split(r"\n    // ", body)[1:]:
        name, _, numbers = block.partition("\n")
        if name.strip() == face:
            return [int(x) for x in re.findall(r"\b\d+\b", numbers)]
    raise SystemExit(f"{face} is not in metrics.rs's {table_name}")
# Measured as nothing, as the browser measures them.
NOTHING = {0x7F, 0xAD}


def row(file: str) -> list[int]:
    font = TTFont(FONTS / file)
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    upm = font["head"].unitsPerEm
    out = []
    for cp in range(FIRST, LAST + 1):
        if cp in NOTHING:
            out.append(0)
        elif cp in cmap:
            out.append(round(hmtx[cmap[cp]][0] * 1000 / upm))
        else:
            out.append(1000)
    return out


def table(name: str, rows: list[tuple[str, list[int]]]) -> str:
    lines = [f"pub const {name}: [[u16; {LAST - FIRST + 1}]; {len(rows)}] = ["]
    for label, values in rows:
        lines.append(f"    // {label}")
        lines.append("    [")
        for i in range(0, len(values), 16):
            lines.append("        " + ", ".join(str(v) for v in values[i : i + 16]) + ",")
        lines.append("    ],")
    lines.append("];")
    return "\n".join(lines)


def text() -> str:
    ids = ", ".join(f'"{f[0]}"' for f in FACES)
    return "\n".join(
        [
            "//! Generated by scripts/fonts/drawing_metrics.py: advance widths of the drawing typefaces the desktop added",
            "//! (Arial, Times New Roman; docs/adr/9311) from their bundled metric twins' files, in thousandths of an em,",
            "//! weight 500 and 600, after the web's typefaces of metrics.rs (`DrawingFont`'s order goes on: 7, 8). Do not",
            "//! edit by hand; run the script again when a face changes.",
            "",
            f"/// The faces, after metrics.rs's seven.",
            f"pub const FONTS: [&str; {len(FACES)}] = [{ids}];",
            "",
            "/// Per face, the advance of each code point from FIRST to LAST, weight 500.",
            table("ADVANCES", [(f[1], row(f[2]) if f[2] else web_row("ADVANCES", "Arimo")) for f in FACES]),
            "",
            "/// The same at 600 (bold).",
            table("BOLD", [(f[1], row(f[3]) if f[3] else web_row("BOLD", "Arimo")) for f in FACES]),
            "",
        ]
    )


def main() -> None:
    made = text()
    if "--check" in sys.argv:
        if OUT.read_text() != made:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date: .run/py/bin/python scripts/fonts/drawing_metrics.py")
        return
    OUT.write_text(made)


if __name__ == "__main__":
    main()
