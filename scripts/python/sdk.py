def emit_modules(model: Model, commands: list[Command]) -> dict[Path, str]:
    em = Emit(model)
    by_ns: dict[tuple[str, ...], list[Command]] = {}
    for c in commands:
        by_ns.setdefault(tuple(c.path), []).append(c)
    # Every namespace with children becomes a package.
    parents = {ns[:i] for ns in by_ns for i in range(1, len(ns))}
    files: dict[Path, str] = {}
    for ns in sorted(set(by_ns) | parents):
        cmds = sorted(by_ns.get(ns, []), key=lambda c: c.attr)
        children = sorted({other[len(ns)] for other in set(by_ns) | parents if len(other) > len(ns) and other[: len(ns)] == ns})
        if ns in parents:
            path = OUT.joinpath(*ns) / "__init__.py"
        else:
            path = module_of(list(ns))
        depth = len(ns) + (1 if ns in parents else 0)
        dots = "." * depth
        used: set[str] = set()
        for c in cmds:
            used.update([c.input, c.output] + ([c.plan] if c.plan else []))
        needs_vec2 = any(
            "Vec2." in build_arg(em, f)
            for c in cmds
            for f in model.structs[c.input].fields
        )
        type_names = sorted(used | ({"Vec2", "Vec2Like"} if needs_vec2 else set()) | referenced_hints(em, model, cmds))
        title = ".".join(["kentos", "cad", *ns])
        lines = [HEADER.rstrip("\n")]
        lines.append(f'"""``{title}``: {", ".join("``" + c.id + "``" for c in cmds) or "its namespaces"}."""')
        lines.append("")
        lines.append("from __future__ import annotations")
        lines.append("")
        if cmds:
            lines.append("from collections.abc import Mapping, Sequence  # noqa: F401")
            lines.append("from typing import TYPE_CHECKING, Any  # noqa: F401")
            lines.append("")
            rt = ["UNSET", "CommandNote", "Unset", "_opt"]
            rt.append("LocalCommand" if any(c.local for c in cmds) else "")
            rt.append("ServerCommand" if any(not c.local for c in cmds) else "")
            rt_names = ", ".join(sorted(n for n in rt if n))
            lines.append(f"from {dots}_runtime import {rt_names}  # noqa: F401")
            lines.append(f"from {dots}types import (  # noqa: F401")
            lines.extend(f"    {n}," for n in type_names)
            lines.append(")")
            lines.append("")
            lines.append("if TYPE_CHECKING:")
            if any(c.local for c in cmds):
                lines.append(f"    from {dots}document import Document")
            if any(not c.local for c in cmds):
                lines.append(f"    from {dots}connection import ProjectRef, TenantRef")
        if children:
            lines.append("")
            for ch in children:
                lines.append(f"from . import {ch}")
        for c in cmds:
            lines.append("")
            lines.append("")
            lines.append(emit_command(em, c).rstrip("\n"))
        names = [c.attr for c in cmds] + children
        lines.append("")
        lines.append("")
        lines.append("__all__ = [" + ", ".join(f'"{n}"' for n in sorted(names)) + "]")
        files[path] = "\n".join(lines) + "\n"
    top = sorted({c.path[0] for c in commands})
    index = [HEADER.rstrip("\n"), '"""Every wrapper by its command\'s id (TODOS.md PY-16)."""', "",
             "from __future__ import annotations", "", "from typing import Any", "",
             "from . import " + ", ".join(top), "", "COMMANDS: dict[str, Any] = {"]
    for c in sorted(commands, key=lambda c: c.id):
        index.append(f'    "{c.id}": {".".join(c.path + [c.attr])},')
    index.append("}")
    index.append('"""The command id → its wrapper (``kentos.cad.polygon.create`` …)."""')
    index.append("")
    index.append("NAMESPACES = (" + ", ".join(f'"{n}"' for n in top) + ",)")
    files[OUT / "_index.py"] = "\n".join(index) + "\n"
    return files


def referenced_hints(em: Emit, model: Model, cmds: list[Command]) -> set[str]:
    """The type names the wrappers' parameter hints mention."""
    names: set[str] = set()

    def walk(t) -> None:
        if isinstance(t, Ref):
            k = model.kind(t.name)
            if k == "enum":
                names.update({t.name, t.name + "Name"})
            elif k == "vec2":
                names.update({"Vec2", "Vec2Like"})
            else:
                names.add(t.name)
        elif isinstance(t, (ListT,)):
            walk(t.item)
        elif isinstance(t, MapT):
            walk(t.value)
        elif isinstance(t, Nullable):
            walk(t.inner)

    for c in cmds:
        for f in model.structs[c.input].fields:
            walk(f.type)
            if f.has_default:
                lit = em.default_literal(f)
                if "." in lit:
                    names.add(lit.split(".")[0])
    return names


