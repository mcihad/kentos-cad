def param_decl(em: Emit, f: Field) -> str:
    hint = em.hint(f.type, loose=True)
    if f.required:
        return f"{f.py}: {hint}"
    if f.has_default:
        lit = em.default_literal(f)
        if is_factory(lit):
            return f"{f.py}: {hint} | Unset = UNSET"
        return f"{f.py}: {hint} = {lit}"
    return f"{f.py}: {hint} | Unset = UNSET"


def convert(em: Emit, t, v: str) -> str:
    """A loose parameter as the dataclass field takes it."""
    if isinstance(t, Nullable):
        inner = convert(em, t.inner, v)
        return v if inner == v else f"_opt({v}, lambda x: {convert(em, t.inner, 'x')})"
    if isinstance(t, Ref) and em.m.kind(t.name) == "vec2":
        return f"Vec2.of({v})"
    if isinstance(t, ListT):
        inner = convert(em, t.item, "p")
        return f"list({v})" if inner == "p" else f"[{inner} for p in {v}]"
    if isinstance(t, MapT):
        return f"dict({v})"
    return v


def build_arg(em: Emit, f: Field) -> str:
    """A wrapper's parameter as its input's field: a point from a pair, a
    list from any sequence; UNSET and None go through as they are."""
    t = f.type.inner if isinstance(f.type, Nullable) else f.type
    if f.required and not isinstance(f.type, Nullable):
        return f"{f.py}={convert(em, t, f.py)}"
    conv = convert(em, t, "x")
    if conv == "x":
        return f"{f.py}={f.py}"
    if f.has_default and is_factory(em.default_literal(f)):
        return f"{f.py}={em.default_literal(f)}() if {f.py} is UNSET else _opt({f.py}, lambda x: {conv})"
    return f"{f.py}=_opt({f.py}, lambda x: {conv})"


def args_doc(fields: list[Field], first: tuple[str, str]) -> str:
    out = ["Args:", f"    {first[0]}: {first[1]}"]
    for f in fields:
        text = doc_text(f.description).split("\n") if f.description else [""]
        out.append(f"    {f.py}: {text[0]}".rstrip())
        out.extend(f"        {line}" if line.strip() else "" for line in text[1:])
    return "\n".join(out)


def emit_command(em: Emit, c: Command) -> str:
    s = em.m.structs.get(c.input)
    if s is None:
        raise Fail(f"{c.id}: its input {c.input} is not a struct")
    fields = s.fields
    cls = "_" + "".join(pascal(p) for p in c.path + [c.attr.rstrip("_")])
    if c.local:
        first = ("doc", "Document", "The drawing it works on.")
    elif c.scope == "project":
        first = ("target", "ProjectRef", "The cloud project (``Connection.project``).")
    else:
        first = ("target", "TenantRef", "The organisation or personal space (``Connection.tenant``).")
    if any(f.py == first[0] for f in fields):
        raise Fail(f"{c.id}: an input field is named {first[0]}")
    params = ["self", f"{first[0]}: {first[1]}", "/", "*"] + [param_decl(em, f) for f in fields]
    if not c.local:
        params += ["expected_versions: Mapping[str, str] | None = None", "idempotency_key: str | None = None"]
    sig = ",\n        ".join(params)
    build = "".join(f"\n            {build_arg(em, f)}," for f in fields)
    make = f"{c.input}({build}\n        )" if fields else f"{c.input}()"
    head = wrap(doc_text(f"{c.title}: {c.summary}"))
    arg_doc = args_doc(fields, (first[0], first[2]))
    if not c.local:
        arg_doc += (
            "\n    expected_versions: The versions the change rests on (``@project``,"
            "\n        ``@file``, an object's id), as the server's envelope carries them."
            "\n    idempotency_key: The same key answers a retry with the same result;"
            "\n        a new one is made when none is given."
        )
    lines = []
    base = f"LocalCommand[{c.input}, {c.output}, {c.plan}]" if c.local else f"ServerCommand[{c.input}, {c.output}]"
    lines.append(f"class {cls}({base}):")
    lines.append(docstring(wrap(f"``{c.id}`` v{c.version}. {doc_text(c.title)}: {doc_text(c.summary)}"), "    ").rstrip("\n"))
    lines.append("    __slots__ = ()")
    lines.append(f'    id = "{c.id}"')
    lines.append(f"    version = {c.version}")
    lines.append(f"    title = {q(c.title)}")
    lines.append(f'    scope = "{c.scope}"')
    lines.append(f"    input_type = {c.input}")
    lines.append(f"    output_type = {c.output}")
    if c.local:
        lines.append(f"    plan_type = {c.plan}")
    call_doc = f"{head}\n\n{arg_doc}\n\nReturns:\n    {c.output}"
    if c.local:
        call_doc += (
            "\n\nRaises:\n    CommandFailed, NeedsInput, RevisionConflict: the command's refusal;"
            "\n        nothing was written. Warnings go to :mod:`warnings` as CommandWarning."
        )
    else:
        call_doc += "\n\nRaises:\n    ServerError: the server's refusal (its code, message and field)."
    target = first[0]
    lines.append("")
    lines.append(f"    def __call__(\n        {sig},\n    ) -> {c.output}:")
    lines.append(docstring(call_doc, "        ").rstrip("\n"))
    if c.local:
        lines.append(f"        return self.execute_input({target}, {make})")
    else:
        lines.append(
            f"        return self.execute_input(\n            {target},\n            {make},\n"
            "            expected_versions=expected_versions,\n            idempotency_key=idempotency_key,\n        )"
        )
    if c.local:
        lines.append("")
        lines.append(f"    def plan(\n        {sig},\n    ) -> {c.plan}:")
        lines.append(docstring(
            "What it would write, with nothing written; the plan's ``revision``, given as\n"
            "``expected_revision``, writes exactly this plan or nothing.", "        ").rstrip("\n"))
        lines.append(f"        return self.plan_input({target}, {make})")
        lines.append("")
        lines.append(f"    def validate(\n        {sig},\n    ) -> list[CommandNote]:")
        lines.append(docstring(
            "Checks the input against the drawing, writing nothing; its warnings.\n"
            "A refusal raises as for the call.", "        ").rstrip("\n"))
        lines.append(f"        return self.validate_input({target}, {make})")
    lines.append("")
    lines.append("")
    lines.append(f"{c.attr} = {cls}()")
    lines.append(f'"""{doc_text(c.title)} (``{c.id}``)."""')
    return "\n".join(lines) + "\n"


def module_of(path: list[str]) -> Path:
    """The file of a namespace: a leaf is a module; one with children a package."""
