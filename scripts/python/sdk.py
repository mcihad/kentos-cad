#!/usr/bin/env python3
"""Generates the typed Python SDK `kentos.cad` from the product command
catalog (docs/adr/0131; TODOS.md PY-10, PY-11, PY-16).

Reads apps/web/src/contracts/generated/commandCatalog.json, which the Rust
contracts write (`KENTOS_WRITE_CATALOG=1 cargo test -p kentos-contracts`),
and writes under python/kentos/cad/:

- types.py: every type of every command's input, output and plan, as the
  catalog's JSON Schemas give them: str enums (with a Literal of their
  names), dataclasses, tagged unions (a base class and one class per
  variant), each with its JSON codec (`to_json`, `from_json`);
- one module per command namespace, a wrapper per command under the
  command's own name (`cad.polygon.create` → `kentos.cad.polygon.create`,
  `project.checkpoint.create` → `kentos.cad.project.checkpoint.create`);
- _index.py: every wrapper by command id.

`--check` compares instead of writing and fails on a difference (CI).
Standard library only.
"""

