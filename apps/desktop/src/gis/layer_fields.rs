    /// Where the box of `id` is drawn.
    fn box_at(
        snapshot: &mut kentos_ui::snapshot::Snapshot,
        app: &crate::app::App,
        id: iced::widget::Id,
    ) -> Option<iced::Rectangle> {
        use iced::Rectangle;
        use iced::advanced::widget::operation::TextInput;
        use iced::advanced::widget::{Id, Operation};
        use std::sync::{Arc, Mutex};
        struct Find(Id, Arc<Mutex<Option<Rectangle>>>);
        impl Operation for Find {
            fn traverse(&mut self, operate: &mut dyn FnMut(&mut dyn Operation)) {
                operate(self);
            }
            fn text_input(&mut self, id: Option<&Id>, bounds: Rectangle, _: &mut dyn TextInput) {
                if id == Some(&self.0) {
                    *self.1.lock().expect("a lock") = Some(bounds);
                }
            }
        }
        let found = Arc::new(Mutex::new(None));
        snapshot.operate(app.view(), Box::new(Find(id, found.clone())));
        *found.lock().expect("a lock")
    }

    /// GIS-003: a press on the second field in the list chooses it at once, so Tekil in the settings is its own; saved,
    /// only the second field changed. With `KENTOS_SHOTS=1` the picture goes to `.run/gui-evidence/gis-003/`.
    #[test]
    fn a_click_into_a_rows_box_chooses_that_row() {
        use kentos_ui::snapshot::Input;
        let mut app = crate::files_testing::app_with_drawing();
        let layer = app
            .document
            .as_ref()
            .expect("open")
            .model
            .layers()
            .active()
            .to_owned();
        let _ = app.update(Message::Run("layer.fields"));
        for (i, name) in ["park_kodu", "bank_sayisi"].into_iter().enumerate() {
            let _ = app.update(msg(Event::Add));
            let _ = app.update(msg(Event::Type(i, Cell::Name, name.into())));
        }
        let _ = app.update(msg(Event::Choose(0)));
        let _ = app.update(msg(Event::Unique(true)));
        let _ = app.update(msg(Event::Save));
        let _ = app.update(Message::Run("layer.fields"));
        let w = app.gis.layer_fields.as_ref().expect("Alanlar is open");
        assert_eq!(w.chosen, Some(0));
        let mut shot = crate::files_testing::offscreen(iced::Size::new(1440., 900.));
        let mut update = |app: &mut crate::app::App, m| drop(app.update(m));
        shot.settle(&mut app, crate::app::App::view, &mut update);
        // The list's second field pressed (docs/adr/9349): its settings are the form's, its name box there.
        let at = crate::files_testing::find_text(&mut shot, &app, "bank_sayisi")
            .expect("the second field in the list");
        shot.input(
            &mut app,
            crate::app::App::view,
            &mut update,
            Input::Click(at.center()),
        );
        assert_eq!(
            app.gis.layer_fields.as_ref().expect("open").chosen,
            Some(1),
            "the clicked row is chosen"
        );
        shot.settle(&mut app, crate::app::App::view, &mut update);
        assert!(
            box_at(&mut shot, &app, cell_id(1, Cell::Name)).is_some(),
            "its name box in the settings"
        );
        crate::files_testing::evidence(&mut shot, &app, "gis-003", "ikinci-satir-secili");
        let _ = app.update(msg(Event::Unique(true)));
        let _ = app.update(msg(Event::Save));
        let doc = &app.document.as_ref().expect("open").model;
        let fields = &doc.layers().get(&layer).expect("the layer").fields;
        let unique: Vec<(&str, bool)> =
            fields.iter().map(|f| (f.name.as_str(), f.unique)).collect();
        assert_eq!(unique, [("park_kodu", true), ("bank_sayisi", true)]);
    }

    #[test]
    fn a_row_writes_its_kinds_own_parts_and_renames_say_old_and_new() {
        let mut r = row_of(&LayerField {
            alias: Some("Kat sayısı".into()),
            min: Some("1".into()),
            ..LayerField::new("Kat", LayerFieldKind::Integer)
        });
        r.size = "5".into();
        r.name = "Katlar".into();
        let f = field_of(&r);
        assert_eq!(
            (f.length, f.scale),
            (None, None),
            "an integer takes no size"
        );
        assert_eq!(f.min.as_deref(), Some("1"));
        assert_eq!(
            renames_of(&[r.clone()]),
            [("Kat".to_owned(), "Katlar".to_owned())]
        );
        r.kind = LayerFieldKind::Text;
        r.size = "x".into();
        assert!(problem_of(&[r]).is_some_and(|p| p.contains("uzunluğu bir tam sayı")));
    }
