// Records the advance widths of the drawing typefaces (app/appearance.ts DRAWING_FONTS) into the geometry
// core (crates/shared/geometry-core/src/text/metrics.rs), so text boxes (picking, zoom extents, exploded
// dimensions) follow the letters the overlay draws instead of a guess of 0.55 em per letter.
//
// Measured where the text is drawn: in Chrome, with the bundled faces, in the weight the overlay uses (500),
// one letter at a time (kerning is left out). Needs a browser: CHROME_BIN=… node scripts/fixtures/record-font-metrics.mjs
// A changed table is a deliberate change of every text box; read the diff.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const WEB = new URL('../../', import.meta.url).pathname;
const OUT = join(WEB, '../../crates/shared/geometry-core/src/text/metrics.rs');
process.chdir(WEB);
const { createServer } = await import(join(WEB, 'node_modules/vite/dist/node/index.js'));
const { launch, sleep } = await import('../e2e/cdp.mjs');

/** Code points measured: Basic Latin, Latin-1 and Latin Extended-A (Turkish letters, °, ±, Ø). */
const FIRST = 0x20;
const LAST = 0x17f;

const server = await createServer({ root: WEB, server: { port: 0, strictPort: false, hmr: false, watch: null }, logLevel: 'error' });
await server.listen();
const b = await launch(server.resolvedUrls.local[0] + '?renderer=webgl2', { width: 800, height: 600 });
let fonts;
try {
  await b.waitFor('window.kentos && window.kentos.view.backendKind.value', 30000);
  await sleep(500);
  fonts = await b.eval(`(async () => {
    const { DRAWING_FONTS } = await import('/src/app/appearance.ts');
    const chars = [];
    for (let c = ${FIRST}; c <= ${LAST}; c++) chars.push(String.fromCharCode(c));
    const g = document.createElement('canvas').getContext('2d');
    const out = [];
    for (const f of DRAWING_FONTS) {
      const family = f.family.split(',')[0];
      await document.fonts.load('500 100px ' + family, chars.join(''));
      if (!document.fonts.check('500 100px ' + family, 'Ağ')) throw new Error(family + ' did not load');
      g.font = '500 1000px ' + f.family;
      out.push({ id: f.id, label: f.label, widths: chars.map((ch) => Math.round(g.measureText(ch).width)) });
    }
    return out;
  })()`);
} finally {
  b.close();
  await server.close();
}

const rows = (w) => {
  const lines = [];
  for (let i = 0; i < w.length; i += 16) lines.push('        ' + w.slice(i, i + 16).join(', ') + ',');
  return lines.join('\n');
};
const count = LAST - FIRST + 1;
const text = `//! Generated by apps/web/scripts/fixtures/record-font-metrics.mjs: advance widths of the drawing
//! typefaces (\`app/appearance.ts\` DRAWING_FONTS) in thousandths of an em, weight 500, measured in
//! Chrome with the bundled faces. Do not edit by hand; record again when a face changes.

/// First and last code point in the tables.
pub const FIRST: u32 = ${FIRST};
pub const LAST: u32 = ${LAST};

/// The faces, in \`DrawingFont\`'s order (${fonts.map((f) => f.id).join(', ')}).
pub const FONTS: [&str; ${fonts.length}] = [${fonts.map((f) => JSON.stringify(f.id)).join(', ')}];

/// Per face, the advance of each code point from FIRST to LAST.
pub const ADVANCES: [[u16; ${count}]; ${fonts.length}] = [
${fonts.map((f) => `    // ${f.label}\n    [\n${rows(f.widths)}\n    ],`).join('\n')}
];
`;
writeFileSync(OUT, text);
console.log(`${OUT}: ${fonts.length} faces × ${count} letters`);
for (const f of fonts) {
  const avg = f.widths.slice(0x61 - FIRST, 0x7a - FIRST + 1).reduce((a, b) => a + b, 0) / 26;
  console.log(`${f.id}: a–z average ${(avg / 1000).toFixed(3)} em`);
}
