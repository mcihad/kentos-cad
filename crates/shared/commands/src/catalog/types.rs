/// The two readers the rows make.
macro_rules! readers {
    ($($id:ident: $input:ty $(=> $output:ty)?;)*) => {
        /// Whether the example `input` of the command `id` parses as the command's input type; none for a command
        /// without a row, so that a new command's examples are always read.
        pub(super) fn input_parses(id: &str, input: &serde_json::Value) -> Option<serde_json::Result<()>> {
            match id {
                $(crate::$id => Some(serde_json::from_value::<$input>(input.clone()).map(|_| ())),)*
                _ => None,
            }
        }

        /// Whether the example `output` of the command `id` parses as the command's output type; none for a command
        /// whose row names no output.
        pub(super) fn output_parses(id: &str, output: &serde_json::Value) -> Option<serde_json::Result<()>> {
            match id {
                $($(crate::$id => Some(serde_json::from_value::<$output>(output.clone()).map(|_| ())),)?)*
                _ => None,
            }
        }
    };
}

command_types!(readers);
