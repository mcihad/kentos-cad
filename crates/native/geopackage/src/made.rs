//! Columns a table makes the values of itself (docs/adr/0754): a generated column, worked out from the row's other
//! columns (SQLite's and PostgreSQL's `GENERATED ALWAYS AS (…) STORED | VIRTUAL`), and an identity's next number
//! (PostgreSQL's `GENERATED { ALWAYS | BY DEFAULT } AS IDENTITY`). Such a column keeps the clause as its default's
//! text, as the table's DDL says it in the default's place, so a field knows what the database gives it and an edit
//! knows what it may not write.

use crate::Column;

/// How a table makes a column's value, as the column's default text says it (docs/adr/0754 §1).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Making {
    /// A plain column, with or without a default: written as given.
    Plain,
    /// `GENERATED BY DEFAULT AS IDENTITY`: a new row's empty value is the identity's next number; written otherwise.
    Identity,
    /// `GENERATED ALWAYS AS IDENTITY`: a new row's value is always the identity's next number; never written.
    IdentityAlways,
    /// `GENERATED ALWAYS AS (…)`: worked out from the row; never written, read again after every write.
    Generated,
}

/// The clause of an identity the table numbers by default.
pub const IDENTITY: &str = "GENERATED BY DEFAULT AS IDENTITY";
/// The clause of an identity the table always numbers.
pub const IDENTITY_ALWAYS: &str = "GENERATED ALWAYS AS IDENTITY";
/// The start of a generated column's clause.
pub const GENERATED: &str = "GENERATED ALWAYS";

impl Making {
    /// How the table makes `c`'s value.
    pub fn of(c: &Column) -> Making {
        match c.default.as_deref() {
            Some(IDENTITY) => Making::Identity,
            Some(IDENTITY_ALWAYS) => Making::IdentityAlways,
            Some(d) if d.starts_with(GENERATED) => Making::Generated,
            _ => Making::Plain,
        }
    }

    /// Whether an edit may write the column: never one the table always makes (PostgreSQL refuses any value but
    /// `DEFAULT`, SQLite any at all).
    pub fn written(self) -> bool {
        !matches!(self, Making::IdentityAlways | Making::Generated)
    }

    /// Whether the column's value changes with the row's others, so a write reads it again.
    pub fn read_back(self) -> bool {
        self == Making::Generated
    }
}

/// A generated column's clause (docs/adr/0754 §1): its expression in parentheses and how it is kept; without the
/// expression (one a table's text does not give) the clause's start alone.
pub fn generated_clause(expression: Option<&str>, stored: bool) -> String {
    let kind = if stored { "STORED" } else { "VIRTUAL" };
    match expression {
        Some(e) => format!("{GENERATED} AS ({e}) {kind}"),
        None => GENERATED.to_owned(),
    }
}

/// A token of SQL text: its kind and its place in the text.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Kind {
    Word,
    Quoted,
    Open,
    Close,
    Comma,
    Other,
}

/// The tokens of SQL text with their byte ranges; comments and blanks left out, a string or a quoted name one token.
pub(crate) fn tokens(sql: &str) -> Vec<(Kind, usize, usize)> {
    let b = sql.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i < b.len() {
        let c = b[i];
        let start = i;
        if c.is_ascii_whitespace() {
            i += 1;
            continue;
        }
        if c == b'-' && b.get(i + 1) == Some(&b'-') {
            while i < b.len() && b[i] != b'\n' {
                i += 1;
            }
            continue;
        }
        if c == b'/' && b.get(i + 1) == Some(&b'*') {
            i += 2;
            while i < b.len() && !(b[i] == b'*' && b.get(i + 1) == Some(&b'/')) {
                i += 1;
            }
            i = (i + 2).min(b.len());
            continue;
        }
        let kind = match c {
            b'(' => {
                i += 1;
                Kind::Open
            }
            b')' => {
                i += 1;
                Kind::Close
            }
            b',' => {
                i += 1;
                Kind::Comma
            }
            b'\'' | b'"' | b'`' | b'[' => {
                let end = if c == b'[' { b']' } else { c };
                i += 1;
                loop {
                    match b.get(i) {
                        None => break,
                        Some(&x) if x == end => {
                            // A doubled quote is the quote itself (not in brackets).
                            if c != b'[' && b.get(i + 1) == Some(&end) {
                                i += 2;
                                continue;
                            }
                            i += 1;
                            break;
                        }
                        Some(_) => i += 1,
                    }
                }
                if c == b'\'' {
                    Kind::Other
                } else {
                    Kind::Quoted
                }
            }
            _ if c == b'_' || c.is_ascii_alphanumeric() || c >= 0x80 => {
                while i < b.len()
                    && (b[i] == b'_'
                        || b[i] == b'$'
                        || b[i].is_ascii_alphanumeric()
                        || b[i] >= 0x80)
                {
                    i += 1;
                }
                Kind::Word
            }
            _ => {
                i += 1;
                Kind::Other
            }
        };
        out.push((kind, start, i));
    }
    out
}

/// A name token's name: a quoted one unquoted, its doubled quotes single.
pub(crate) fn name_of(sql: &str, (kind, a, b): (Kind, usize, usize)) -> String {
    let t = &sql[a..b];
    if kind != Kind::Quoted || t.len() < 2 {
        return t.to_owned();
    }
    let inner = &t[1..t.len() - 1];
    match t.as_bytes()[0] {
        b'"' => inner.replace("\"\"", "\""),
        b'`' => inner.replace("``", "`"),
        _ => inner.to_owned(),
    }
}

/// A token: its kind and its byte range.
pub(crate) type Token = (Kind, usize, usize);

/// A `CREATE TABLE` text's definitions: the tokens between the commas of its outer parentheses.
pub(crate) fn definitions(t: &[Token]) -> Option<Vec<&[Token]>> {
    let open = t.iter().position(|x| x.0 == Kind::Open)?;
    let mut defs: Vec<&[Token]> = Vec::new();
    let mut depth = 0usize;
    let mut start = open + 1;
    for (k, x) in t.iter().enumerate().skip(open + 1) {
        match x.0 {
            Kind::Open => depth += 1,
            Kind::Close if depth == 0 => {
                defs.push(&t[start..k]);
                return Some(defs);
            }
            Kind::Close => depth -= 1,
            Kind::Comma if depth == 0 => {
                defs.push(&t[start..k]);
                start = k + 1;
            }
            _ => {}
        }
    }
    Some(defs)
}

/// The generation expression of `column` in a table's `CREATE TABLE` text (docs/adr/0754 §1): the text inside the
/// parentheses after the `AS` of the column's definition, as written; none when the definition or its `AS (` is not
/// found. Names are compared as SQLite compares them (ASCII letters' case aside).
pub fn generation_of(create: &str, column: &str) -> Option<String> {
    let t = tokens(create);
    let defs = definitions(&t)?;
    let def = defs.into_iter().find(|d| {
        d.first().is_some_and(|&n| {
            matches!(n.0, Kind::Word | Kind::Quoted)
                && name_of(create, n).eq_ignore_ascii_case(column)
        })
    })?;
    // `AS (` at the definition's own depth (an `AS` inside a CHECK or DEFAULT's parentheses is not it).
    let mut depth = 0usize;
    for (k, x) in def.iter().enumerate() {
        match x.0 {
            Kind::Open => depth += 1,
            Kind::Close => depth = depth.saturating_sub(1),
            Kind::Word if depth == 0 && create[x.1..x.2].eq_ignore_ascii_case("AS") => {
                let next = def.get(k + 1)?;
                if next.0 != Kind::Open {
                    continue;
                }
                let mut inner = 0usize;
                for y in &def[k + 2..] {
                    match y.0 {
                        Kind::Open => inner += 1,
                        Kind::Close if inner == 0 => {
                            let text = create[next.2..y.1].trim();
                            return (!text.is_empty()).then(|| text.to_owned());
                        }
                        Kind::Close => inner -= 1,
                        _ => {}
                    }
                }
                return None;
            }
            _ => {}
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ColumnKind;

    fn column(default: Option<&str>) -> Column {
        Column {
            name: "x".into(),
            decl: String::new(),
            kind: ColumnKind::Text(None),
            not_null: false,
            default: default.map(str::to_owned),
        }
    }

    #[test]
    fn a_clause_says_how_the_table_makes_the_value() {
        assert_eq!(Making::of(&column(None)), Making::Plain);
        assert_eq!(Making::of(&column(Some("now()"))), Making::Plain);
        assert_eq!(Making::of(&column(Some(IDENTITY))), Making::Identity);
        assert_eq!(
            Making::of(&column(Some(IDENTITY_ALWAYS))),
            Making::IdentityAlways
        );
        let generated = generated_clause(Some("upper(ad)"), true);
        assert_eq!(generated, "GENERATED ALWAYS AS (upper(ad)) STORED");
        assert_eq!(Making::of(&column(Some(&generated))), Making::Generated);
        assert_eq!(Making::of(&column(Some(GENERATED))), Making::Generated);
        assert!(Making::Identity.written() && Making::Plain.written());
        assert!(!Making::IdentityAlways.written() && !Making::Generated.written());
        assert!(Making::Generated.read_back() && !Making::IdentityAlways.read_back());
    }

    /// docs/adr/0754's timing: 10 000 rows' codes updated in a table that works out five columns from them (never set,
    /// read again), against the same table whose five columns are plain and set (`cargo test --release -p
    /// kentos-geopackage --lib made::tests::timing -- --ignored --nocapture`).
    #[test]
    #[ignore = "a timing, run by hand"]
    fn timing() {
        use crate::{Edits, GeoPackage, NewRow, Value};
        const ROWS: i64 = 10_000;
        for generated in [false, true] {
            let path = std::env::temp_dir().join(format!(
                "kentos-made-{generated}-{}.gpkg",
                std::process::id()
            ));
            let _ = std::fs::remove_file(&path);
            let mut g = GeoPackage::create(&path).expect("made");
            let made = |e: &str, kind: &str| {
                if generated {
                    format!("GENERATED ALWAYS AS ({e}) {kind}")
                } else {
                    String::new()
                }
            };
            g.conn
                .execute_batch(&format!(
                    "CREATE TABLE parsel (fid INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, kod TEXT NOT NULL, ad TEXT, \
                     ana TEXT {}, d1 TEXT {}, d2 TEXT {}, birlesik TEXT {}, seviye INTEGER {});
                     INSERT INTO gpkg_contents (table_name, data_type, identifier) VALUES ('parsel', 'attributes', 'parsel');",
                    made("substr(kod, 1, instr(kod || '.', '.') - 1)", "STORED"),
                    made("nullif(substr(kod, 5, 2), '')", "VIRTUAL"),
                    made("nullif(substr(kod, 8, 2), '')", "VIRTUAL"),
                    made("replace(kod, '.', '')", "STORED"),
                    made("length(kod) - length(replace(kod, '.', '')) + 1", "STORED"),
                ))
                .expect("the table");
            g.conn.execute_batch("BEGIN").expect("begin");
            for i in 1..=ROWS {
                g.conn
                    .execute(
                        "INSERT INTO parsel (fid, kod, ad) VALUES (?1, ?2, ?3)",
                        rusqlite::params![
                            i,
                            format!("{:03}.{:02}.{:02}", i % 900 + 100, i % 97, i % 89),
                            "Hesap"
                        ],
                    )
                    .expect("a row");
            }
            g.conn.execute_batch("COMMIT").expect("commit");
            let layer = g
                .layers()
                .expect("layers")
                .into_iter()
                .find(|l| l.name == "parsel")
                .expect("the table");
            assert_eq!(
                layer
                    .columns
                    .iter()
                    .filter(|c| Making::of(c) == Making::Generated)
                    .count(),
                if generated { 5 } else { 0 }
            );
            let mut best = f64::MAX;
            for round in 0..5_i64 {
                let edits = Edits {
                    update: (1..=ROWS)
                        .map(|fid| {
                            let mut values = vec![Value::Null; layer.columns.len()];
                            values[0] = Value::Text(format!(
                                "{:03}.{:02}.{:02}",
                                (fid + round) % 900 + 100,
                                fid % 97,
                                round
                            ));
                            values[1] = Value::Text("Hesap".into());
                            (
                                fid,
                                NewRow {
                                    fid: None,
                                    geometry: None,
                                    values,
                                },
                            )
                        })
                        .collect(),
                    ..Edits::default()
                };
                let t = std::time::Instant::now();
                let written = g.edit_many(&[(&layer, &edits)], &[]).expect("edited");
                best = best.min(t.elapsed().as_secs_f64() * 1000.0);
                assert_eq!(
                    written[0].refreshed.len(),
                    if generated { ROWS as usize } else { 0 }
                );
            }
            println!(
                "{} sütunla 10 000 satırın güncellenmesi: {best:.1} ms (5 denemenin en iyisi)",
                if generated {
                    "beş hesaplanan"
                } else {
                    "beş düz"
                }
            );
            drop(g);
            let _ = std::fs::remove_file(path);
        }
    }

    #[test]
    fn a_generation_expression_is_read_from_the_tables_text() {
        let sql = r#"CREATE TABLE "parsel" ( -- the parcels
            "fid" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, "geom" POLYGON,
            "kod" TEXT NOT NULL CHECK (CAST(length(kod) AS INTEGER) > 0),
            "ana" TEXT GENERATED ALWAYS AS (substr(kod, 1, instr(kod || '.', '.') - 1)) STORED,
            [Birleşik "Kod"] TEXT AS (replace(kod, '.', '')),
            `etiket` TEXT AS ( ada || '/' || "parsel" ) VIRTUAL, /* a comment, with a comma ( */
            durum TEXT DEFAULT (CAST(1 AS TEXT)),
            seviye INTEGER NOT NULL GENERATED ALWAYS AS (CASE
                WHEN kod = '' THEN 0
                ELSE length(kod) - length(replace(kod, '.', '')) + 1 END) STORED,
            "tırnak""lı" TEXT AS ('a)b'),
            UNIQUE (kod)
        )"#;
        assert_eq!(
            generation_of(sql, "ANA").as_deref(),
            Some("substr(kod, 1, instr(kod || '.', '.') - 1)")
        );
        assert_eq!(
            generation_of(sql, "Birleşik \"Kod\"").as_deref(),
            Some("replace(kod, '.', '')")
        );
        assert_eq!(
            generation_of(sql, "etiket").as_deref(),
            Some("ada || '/' || \"parsel\"")
        );
        assert_eq!(
            generation_of(sql, "seviye").map(|s| s.split_whitespace().collect::<Vec<_>>().join(" ")),
            Some("CASE WHEN kod = '' THEN 0 ELSE length(kod) - length(replace(kod, '.', '')) + 1 END".into())
        );
        assert_eq!(generation_of(sql, "tırnak\"lı").as_deref(), Some("'a)b'"));
        assert_eq!(
            generation_of(sql, "kod"),
            None,
            "an AS inside CHECK is not a generation"
        );
        assert_eq!(
            generation_of(sql, "durum"),
            None,
            "nor one inside DEFAULT's parentheses"
        );
        assert_eq!(generation_of(sql, "yok"), None);
        assert_eq!(
            generation_of("CREATE TABLE t (a AS (", "a"),
            None,
            "an unfinished text"
        );
        assert_eq!(generation_of("", "a"), None);
    }
}
